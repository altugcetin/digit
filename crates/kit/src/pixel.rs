pub fn cells(text: &str) -> (Vec<(usize, usize)>, usize, usize) {
    let mut out = Vec::new();
    let mut x = 0;
    let mut deep = false;
    for (i, c) in text.chars().enumerate() {
        if i > 0 {
            x += 1;
        }
        let rows = glyph(c);
        deep |= rows.len() > 7;
        let w = rows.iter().map(|r| r.len()).max().unwrap_or(3);
        for (y, row) in rows.iter().enumerate().take(ROWS) {
            for (cx, b) in row.bytes().enumerate() {
                if b == b'#' {
                    out.push((x + cx, y));
                }
            }
        }
        x += w;
    }
    (out, x, if deep { ROWS } else { 7 })
}

pub fn outline(text: &str) -> (Vec<Vec<(i32, i32)>>, usize, usize) {
    let (dots, w, h) = cells(text);
    let set: std::collections::HashSet<(i32, i32)> = dots.iter().map(|&(x, y)| (x as i32, y as i32)).collect();
    let mut next: std::collections::BTreeMap<(i32, i32), Vec<(i32, i32)>> = std::collections::BTreeMap::new();
    let mut edge = |a: (i32, i32), b: (i32, i32)| next.entry(a).or_default().push(b);
    for &(x, y) in &dots {
        let (x, y) = (x as i32, y as i32);
        if !set.contains(&(x, y - 1)) {
            edge((x, y), (x + 1, y));
        }
        if !set.contains(&(x + 1, y)) {
            edge((x + 1, y), (x + 1, y + 1));
        }
        if !set.contains(&(x, y + 1)) {
            edge((x + 1, y + 1), (x, y + 1));
        }
        if !set.contains(&(x - 1, y)) {
            edge((x, y + 1), (x, y));
        }
    }
    let starts: Vec<(i32, i32)> = next.keys().copied().collect();
    let mut loops = Vec::new();
    for start in starts {
        while let Some(first) = next.get_mut(&start).and_then(Vec::pop) {
            let mut pts = vec![start];
            let mut cur = first;
            while cur != start {
                pts.push(cur);
                match next.get_mut(&cur).and_then(Vec::pop) {
                    Some(n) => cur = n,
                    None => break,
                }
            }
            let n = pts.len();
            let corners: Vec<(i32, i32)> = (0..n)
                .filter(|&i| {
                    let (a, b, c) = (pts[(i + n - 1) % n], pts[i], pts[(i + 1) % n]);
                    !((a.0 == b.0 && b.0 == c.0) || (a.1 == b.1 && b.1 == c.1))
                })
                .map(|i| pts[i])
                .collect();
            if corners.len() >= 4 {
                loops.push(corners);
            }
        }
    }
    (loops, w, h)
}

fn num(v: f64) -> String {
    let r = (v * 100.0).round() / 100.0;
    if r.fract() == 0.0 { format!("{}", r as i64) } else { format!("{r}") }
}

pub fn path(text: &str, cell: f64, ox: f64, oy: f64) -> (String, usize, usize) {
    let (loops, w, h) = outline(text);
    let mut d = String::new();
    for l in loops {
        for (i, (x, y)) in l.iter().enumerate() {
            d.push(if i == 0 { 'M' } else { 'L' });
            d.push_str(&num(ox + *x as f64 * cell));
            d.push(' ');
            d.push_str(&num(oy + *y as f64 * cell));
        }
        d.push('Z');
    }
    (d, w, h)
}

pub fn trace(cr: &cairo::Context, text: &str, cell: f64, ox: f64, oy: f64) {
    for l in outline(text).0 {
        for (i, (x, y)) in l.iter().enumerate() {
            let (px, py) = (ox + *x as f64 * cell, oy + *y as f64 * cell);
            if i == 0 {
                cr.move_to(px, py);
            } else {
                cr.line_to(px, py);
            }
        }
        cr.close_path();
    }
}

pub fn svg(text: &str, cell: usize, ink: &str) -> String {
    let (d, w, h) = path(text, cell as f64, 0.0, 0.0);
    format!(r#"<svg xmlns="http://www.w3.org/2000/svg" width="{}" height="{}"><path d="{d}" fill="{ink}"/></svg>"#, w * cell, h * cell)
}

#[cfg(test)]
mod tests {
    use super::{cells, outline, path};

    #[test]
    fn measures_words() {
        let (dots, w, h) = cells("Digit");
        assert_eq!(w, 5 + 1 + 1 + 1 + 4 + 1 + 1 + 1 + 3);
        assert_eq!(h, 9);
        assert!(dots.iter().all(|(x, y)| *x < w && *y < h));
        assert_eq!(cells("I").1, 3);
    }

    #[test]
    fn outlines_cover_exactly_the_cells() {
        for word in ["Digit", "d", "s", "o", "x", "Mw", "0"] {
            let (dots, _, _) = cells(word);
            let (loops, _, _) = outline(word);
            let area: i64 = loops
                .iter()
                .map(|l| (0..l.len()).map(|i| {
                    let (a, b) = (l[i], l[(i + 1) % l.len()]);
                    a.0 as i64 * b.1 as i64 - b.0 as i64 * a.1 as i64
                }).sum::<i64>())
                .sum();
            assert_eq!(area / 2, dots.len() as i64, "{word}");
            assert!(loops.iter().flatten().zip(loops.iter().flatten().skip(1)).all(|(a, b)| a != b));
        }
        assert_eq!(outline("o").0.len(), 2);
        assert_eq!(outline("I").0.len(), 1);
        assert_eq!(path("I", 2.0, 1.0, 0.0).0.matches('M').count(), 1);
    }
}
